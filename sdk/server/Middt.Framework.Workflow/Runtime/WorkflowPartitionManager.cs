    /// <summary>
    /// Ensures flow partitions and flow-specific indexes exist for all registered workflows.
    /// </summary>
    public static async Task EnsurePartitionsAndIndexesAsync(
        WorkflowDbContext db,
        WorkflowRegistry registry,
        string? schema,
        ILogger? logger,
        CancellationToken cancellationToken)
    {
        var provider = db.Database.ProviderName ?? string.Empty;
        var isPostgres = provider.Contains("Npgsql", StringComparison.Ordinal);
        var isSqlite = provider.Contains("Sqlite", StringComparison.Ordinal);

        if (!isPostgres && !isSqlite)
        {
            return;
        }

        var validatedSchema = isPostgres ? ValidateIdentifier(schema) : string.Empty;
        var isPartitioned = isPostgres && await IsPartitionedTableAsync(db, schema, "WorkflowInstances", cancellationToken);

        if (isPostgres && !isPartitioned)
        {
            var unpartitionedExists = await IsUnpartitionedTableAsync(db, schema, "WorkflowInstances", cancellationToken);
            if (unpartitionedExists)
            {
                await MigrateExistingTablesToPartitionedAsync(db, registry, schema, logger, cancellationToken);
                isPartitioned = true;
            }
        }

        if (isPostgres && isPartitioned)
        {
            await EnsureDefaultPartitionsAsync(db, validatedSchema, logger, cancellationToken);
        }

        foreach (var definition in registry.Latest)
        {
            var workflowKey = definition.Key;
            var suffix = PartitionSuffix(workflowKey);

            if (isPostgres && isPartitioned)
            {
                await EnsureFlowPartitionsAsync(db, validatedSchema, workflowKey, suffix, logger, cancellationToken);
            }

            await EnsureFlowIndexesAsync(db, definition, validatedSchema, suffix, isPostgres, isPartitioned, logger, cancellationToken);
        }

        if (isPostgres)
        {
            await EnsureGlobalIndexesAsync(db, validatedSchema, logger, cancellationToken);
        }
    }

    private static async Task EnsureDefaultPartitionsAsync(WorkflowDbContext db, string schema, ILogger? logger, CancellationToken cancellationToken)
    {
        var defaultTables = new[]
        {
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowInstances_Default\" PARTITION OF {schema}.\"WorkflowInstances\" DEFAULT;",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowInstanceData_Default\" PARTITION OF {schema}.\"WorkflowInstanceData\" DEFAULT;",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowHistory_Default\" PARTITION OF {schema}.\"WorkflowHistory\" DEFAULT;",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowJobs_Default\" PARTITION OF {schema}.\"WorkflowJobs\" DEFAULT;",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowIncidents_Default\" PARTITION OF {schema}.\"WorkflowIncidents\" DEFAULT;",
        };

        foreach (var sql in defaultTables)
        {
            await ExecuteSafeAsync(db, sql, logger, cancellationToken);
        }
    }

    private static async Task EnsureFlowPartitionsAsync(WorkflowDbContext db, string schema, string workflowKey, string suffix, ILogger? logger, CancellationToken cancellationToken)
    {
        var escapedKey = workflowKey.Replace("'", "''", StringComparison.Ordinal);
        var rawSchema = schema.Trim('"');
        var migrateAndCreateSql = $"""
            DO $$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1
                    FROM pg_class c
                    JOIN pg_namespace n ON c.relnamespace = n.oid
                    WHERE n.nspname = '{rawSchema}' AND c.relname = 'WorkflowInstances_{suffix}'
                ) THEN
                    CREATE TEMP TABLE "_tmp_wi_{suffix}" ON COMMIT DROP AS
                        SELECT * FROM {schema}."WorkflowInstances_Default" WHERE "WorkflowKey" = '{escapedKey}';
                    CREATE TEMP TABLE "_tmp_wid_{suffix}" ON COMMIT DROP AS
                        SELECT * FROM {schema}."WorkflowInstanceData_Default" WHERE "WorkflowKey" = '{escapedKey}';
                    CREATE TEMP TABLE "_tmp_wh_{suffix}" ON COMMIT DROP AS
                        SELECT * FROM {schema}."WorkflowHistory_Default" WHERE "WorkflowKey" = '{escapedKey}';
                    CREATE TEMP TABLE "_tmp_wj_{suffix}" ON COMMIT DROP AS
                        SELECT * FROM {schema}."WorkflowJobs_Default" WHERE "WorkflowKey" = '{escapedKey}';
                    CREATE TEMP TABLE "_tmp_winc_{suffix}" ON COMMIT DROP AS
                        SELECT * FROM {schema}."WorkflowIncidents_Default" WHERE "WorkflowKey" = '{escapedKey}';

                    DELETE FROM {schema}."WorkflowInstanceData_Default" WHERE "WorkflowKey" = '{escapedKey}';
                    DELETE FROM {schema}."WorkflowInstances_Default" WHERE "WorkflowKey" = '{escapedKey}';
                    DELETE FROM {schema}."WorkflowHistory_Default" WHERE "WorkflowKey" = '{escapedKey}';
                    DELETE FROM {schema}."WorkflowJobs_Default" WHERE "WorkflowKey" = '{escapedKey}';
                    DELETE FROM {schema}."WorkflowIncidents_Default" WHERE "WorkflowKey" = '{escapedKey}';

                    CREATE TABLE IF NOT EXISTS {schema}."WorkflowInstances_{suffix}" PARTITION OF {schema}."WorkflowInstances" FOR VALUES IN ('{escapedKey}');
                    CREATE TABLE IF NOT EXISTS {schema}."WorkflowInstanceData_{suffix}" PARTITION OF {schema}."WorkflowInstanceData" FOR VALUES IN ('{escapedKey}');
                    CREATE TABLE IF NOT EXISTS {schema}."WorkflowHistory_{suffix}" PARTITION OF {schema}."WorkflowHistory" FOR VALUES IN ('{escapedKey}');
                    CREATE TABLE IF NOT EXISTS {schema}."WorkflowJobs_{suffix}" PARTITION OF {schema}."WorkflowJobs" FOR VALUES IN ('{escapedKey}');
                    CREATE TABLE IF NOT EXISTS {schema}."WorkflowIncidents_{suffix}" PARTITION OF {schema}."WorkflowIncidents" FOR VALUES IN ('{escapedKey}');

                    INSERT INTO {schema}."WorkflowInstances" SELECT * FROM "_tmp_wi_{suffix}";
                    INSERT INTO {schema}."WorkflowInstanceData" SELECT * FROM "_tmp_wid_{suffix}";
                    INSERT INTO {schema}."WorkflowHistory" SELECT * FROM "_tmp_wh_{suffix}";
                    INSERT INTO {schema}."WorkflowJobs" SELECT * FROM "_tmp_wj_{suffix}";
                    INSERT INTO {schema}."WorkflowIncidents" SELECT * FROM "_tmp_winc_{suffix}";

                    DROP TABLE "_tmp_wi_{suffix}", "_tmp_wid_{suffix}", "_tmp_wh_{suffix}", "_tmp_wj_{suffix}", "_tmp_winc_{suffix}";
                END IF;
            END $$;
            """;

        await ExecuteSafeAsync(db, migrateAndCreateSql, logger, cancellationToken);
    }

    private static async Task EnsureFlowIndexesAsync(
        WorkflowDbContext db,
        WorkflowDefinition definition,
        string schema,
        string suffix,
        bool isPostgres,
        bool isPartitioned,
        ILogger? logger,
        CancellationToken cancellationToken)
    {
        var targetTable = isPostgres && isPartitioned
            ? $"{schema}.\"WorkflowInstanceData_{suffix}\""
            : (isPostgres ? $"{schema}.\"WorkflowInstanceData\"" : "\"WorkflowInstanceData\"");

        var escapedKey = definition.Key.Replace("'", "''", StringComparison.Ordinal);
        var expectedIndexes = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var (propName, propType) in ExtractIndexedProperties(definition))
        {
            var cleanProp = CleanIdentifier(propName);
            var indexName = $"IX_Part_{suffix}_{cleanProp}";
            expectedIndexes.Add(indexName);

            string sql;
            if (isPostgres && isPartitioned)
            {
                var expr = propType switch
                {
                    "number" or "integer" => $"((((\"Data\"->>'{propName}')::numeric)))",
                    "boolean" => $"((((\"Data\"->>'{propName}')::boolean)))",
                    _ => $"(((\"Data\"->>'{propName}')::text))",
                };
                sql = $"CREATE INDEX IF NOT EXISTS \"{indexName}\" ON {targetTable} ({expr});";
            }
            else if (isPostgres)
            {
                var expr = propType switch
                {
                    "number" or "integer" => $"((((\"Data\"->>'{propName}')::numeric)))",
                    "boolean" => $"((((\"Data\"->>'{propName}')::boolean)))",
                    _ => $"(((\"Data\"->>'{propName}')::text))",
                };
                sql = $"CREATE INDEX IF NOT EXISTS \"{indexName}\" ON {targetTable} ({expr}) WHERE \"WorkflowKey\" = '{escapedKey}';";
            }
            else
            {
                sql = $"CREATE INDEX IF NOT EXISTS \"{indexName}\" ON {targetTable} (json_extract(\"Data\", '$.{propName}')) WHERE \"WorkflowKey\" = '{escapedKey}';";
            }

            await ExecuteSafeAsync(db, sql, logger, cancellationToken);
        }

        // Drop any stale IX_Part_{suffix}_* indexes that are no longer part of the workflow's indexed properties.
        await DropStaleFlowIndexesAsync(db, schema, suffix, isPostgres, expectedIndexes, logger, cancellationToken);
    }

    private static async Task DropStaleFlowIndexesAsync(
        WorkflowDbContext db,
        string schema,
        string suffix,
        bool isPostgres,
        HashSet<string> expectedIndexes,
        ILogger? logger,
        CancellationToken cancellationToken)
    {
        try
        {
            var prefix = $"IX_Part_{suffix}_%";
            List<string> existing;
            if (isPostgres)
            {
                var rawSchema = schema.Trim('"');
                existing = await db.Database
                    .SqlQuery<string>($"SELECT indexname AS \"Value\" FROM pg_indexes WHERE schemaname = {rawSchema} AND indexname LIKE {prefix}")
                    .ToListAsync(cancellationToken);
            }
            else
            {
                existing = await db.Database
                    .SqlQuery<string>($"SELECT name AS \"Value\" FROM sqlite_master WHERE type = 'index' AND name LIKE {prefix}")
                    .ToListAsync(cancellationToken);
            }

            foreach (var indexName in existing)
            {
                if (!expectedIndexes.Contains(indexName) && SafeIdRegex.IsMatch(indexName))
                {
                    var dropSql = isPostgres
                        ? $"DROP INDEX IF EXISTS {schema}.\"{indexName}\";"
                        : $"DROP INDEX IF EXISTS \"{indexName}\";";
                    await ExecuteSafeAsync(db, dropSql, logger, cancellationToken);
                }
            }
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            logger?.LogDebug(ex, "Skipped stale flow index cleanup for {Suffix}", suffix);
        }
    }

    private static async Task EnsureGlobalIndexesAsync(WorkflowDbContext db, string schema, ILogger? logger, CancellationToken cancellationToken)
    {
        var globalIndexStatements = new[]
        {
            $"CREATE INDEX IF NOT EXISTS \"IX_WorkflowInstanceData_Data_GIN\" ON {schema}.\"WorkflowInstanceData\" USING gin (\"Data\" jsonb_path_ops);",
            $"CREATE INDEX IF NOT EXISTS \"IX_WorkflowHistory_Data_GIN\" ON {schema}.\"WorkflowHistory\" USING gin (\"Data\" jsonb_path_ops);",
        };

        foreach (var sql in globalIndexStatements)
        {
            await ExecuteSafeAsync(db, sql, logger, cancellationToken);
        }
    }

    private static async Task<bool> IsPartitionedTableAsync(WorkflowDbContext db, string? schema, string table, CancellationToken cancellationToken)
    {
        try
        {
            var targetSchema = string.IsNullOrWhiteSpace(schema) ? "public" : schema;
            var count = await db.Database.SqlQuery<int>($"""
                SELECT CAST(COUNT(*) AS int) AS "Value"
                FROM pg_partitioned_table pt
                JOIN pg_class c ON pt.partrelid = c.oid
                JOIN pg_namespace n ON c.relnamespace = n.oid
                WHERE n.nspname = {targetSchema} AND c.relname = {table}
                """).SingleAsync(cancellationToken);
            return count > 0;
        }
        catch
        {
            return false;
        }
    }

    private static async Task<bool> IsUnpartitionedTableAsync(WorkflowDbContext db, string? schema, string table, CancellationToken cancellationToken)
    {
        try
        {
            var targetSchema = string.IsNullOrWhiteSpace(schema) ? "public" : schema;
            var count = await db.Database.SqlQuery<int>($"""
                SELECT CAST(COUNT(*) AS int) AS "Value"
                FROM pg_class c
                JOIN pg_namespace n ON c.relnamespace = n.oid
                WHERE n.nspname = {targetSchema} AND c.relname = {table} AND c.relkind = 'r'
                """).SingleAsync(cancellationToken);
            return count > 0;
        }
        catch
        {
            return false;
        }
    }

    private static async Task MigrateExistingTablesToPartitionedAsync(
        WorkflowDbContext db,
        WorkflowRegistry registry,
        string? schema,
        ILogger? logger,
        CancellationToken cancellationToken)
    {
        var validatedSchema = ValidateIdentifier(schema);
        var targetSchema = string.IsNullOrWhiteSpace(schema) ? "public" : schema;

        logger?.LogInformation("Migrating workflow tables in schema {Schema} to declarative partitioned tables...", targetSchema);

        // 1. Ensure WorkflowKey column is populated on all 5 existing tables
        await EnsureWorkflowKeyDataBackfilledAsync(db, validatedSchema, cancellationToken);

        // 2. Drop existing foreign key and rename tables to temporary names
        var renameStatements = new[]
        {
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowInstanceData\" DROP CONSTRAINT IF EXISTS \"FK_WorkflowInstanceData_WorkflowInstances_InstanceId\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowInstanceData\" DROP CONSTRAINT IF EXISTS \"FK_WorkflowInstanceData_Instances\";",

            $"ALTER TABLE {validatedSchema}.\"WorkflowInstances\" RENAME TO \"_old_WorkflowInstances\";",
            $"ALTER TABLE {validatedSchema}.\"WorkflowInstanceData\" RENAME TO \"_old_WorkflowInstanceData\";",
            $"ALTER TABLE {validatedSchema}.\"WorkflowJobs\" RENAME TO \"_old_WorkflowJobs\";",
            $"ALTER TABLE {validatedSchema}.\"WorkflowHistory\" RENAME TO \"_old_WorkflowHistory\";",
            $"ALTER TABLE {validatedSchema}.\"WorkflowIncidents\" RENAME TO \"_old_WorkflowIncidents\";",

            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowInstances\" RENAME CONSTRAINT \"PK_WorkflowInstances\" TO \"_old_PK_WorkflowInstances\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowInstanceData\" RENAME CONSTRAINT \"PK_WorkflowInstanceData\" TO \"_old_PK_WorkflowInstanceData\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowJobs\" RENAME CONSTRAINT \"PK_WorkflowJobs\" TO \"_old_PK_WorkflowJobs\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowHistory\" RENAME CONSTRAINT \"PK_WorkflowHistory\" TO \"_old_PK_WorkflowHistory\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowIncidents\" RENAME CONSTRAINT \"PK_WorkflowIncidents\" TO \"_old_PK_WorkflowIncidents\";",
        };

        foreach (var sql in renameStatements)
        {
            try
            {
#pragma warning disable EF1002
                await db.Database.ExecuteSqlRawAsync(sql, cancellationToken);
#pragma warning restore EF1002
            }
            catch (Exception ex)
            {
                logger?.LogDebug(ex, "Rename statement skipped: {Sql}", sql);
            }
        }

        // Drop any indexes on the old tables so index names are free for the new partitioned tables
        var dropOldIndexes = $"""
            DO $$
            DECLARE
                r RECORD;
            BEGIN
                FOR r IN (
                    SELECT indexname
                    FROM pg_indexes
                    WHERE schemaname = '{targetSchema}'
                      AND tablename IN ('_old_WorkflowInstances', '_old_WorkflowInstanceData', '_old_WorkflowJobs', '_old_WorkflowHistory', '_old_WorkflowIncidents')
                ) LOOP
                    EXECUTE 'DROP INDEX IF EXISTS {validatedSchema}."' || r.indexname || '" CASCADE;';
                END LOOP;
            END $$;
        """;
#pragma warning disable EF1002
        try { await db.Database.ExecuteSqlRawAsync(dropOldIndexes, cancellationToken); } catch { }
#pragma warning restore EF1002

        // 3. Create the 5 partitioned root tables
        await CreatePartitionedTablesAsync(db, schema, cancellationToken);

        // 4. Ensure default fallback partitions
        await EnsureDefaultPartitionsAsync(db, validatedSchema, logger, cancellationToken);

        // 5. Ensure flow-specific partitions for all registered flows
        foreach (var definition in registry.Latest)
        {
            var suffix = PartitionSuffix(definition.Key);
            await EnsureFlowPartitionsAsync(db, validatedSchema, definition.Key, suffix, logger, cancellationToken);
        }

        // 6. Copy all existing data from _old_* tables into the newly created partitioned tables
        var copyStatements = new[]
        {
            $"""
            INSERT INTO {validatedSchema}."WorkflowInstances"
            SELECT "Id", "WorkflowKey", "WorkflowVersion", "BusinessKey", "State", "Status",
                   "PendingTransition", "PendingInput", "StartedBy", "LastExecutedBy", "Revision",
                   "BusySince", "ParentInstanceId", "WaitingForInstanceId", "Error", "CreatedAt",
                   "UpdatedAt", "CompletedAt"
            FROM {validatedSchema}."_old_WorkflowInstances";
            """,
            $"""
            INSERT INTO {validatedSchema}."WorkflowInstanceData"
            SELECT "InstanceId", "WorkflowKey", "Data", "DataVersion", "DataHash", "ETag", "UpdatedAt"
            FROM {validatedSchema}."_old_WorkflowInstanceData";
            """,
            $"""
            INSERT INTO {validatedSchema}."WorkflowJobs"
            SELECT "Id", "InstanceId", "WorkflowKey", "Kind", "TransitionKey", "State", "Payload",
                   "RequestedBy", "DueAt", "LockedUntil", "Attempts", "LastError", "CreatedAt"
            FROM {validatedSchema}."_old_WorkflowJobs";
            """,
            $"""
            INSERT INTO {validatedSchema}."WorkflowHistory"
            SELECT "Id", "InstanceId", "WorkflowKey", "TransitionKey", "FromState", "ToState",
                   "Trigger", "ExecutedBy", "Input", "DataVersion", "Data", "Tasks", "StartedAt",
                   "FinishedAt"
            FROM {validatedSchema}."_old_WorkflowHistory";
            """,
            $"""
            INSERT INTO {validatedSchema}."WorkflowIncidents"
            SELECT "Id", "InstanceId", "WorkflowKey", "State", "TransitionKey", "TaskKey", "Error",
                   "Attempts", "CreatedAt", "ResolvedAt"
            FROM {validatedSchema}."_old_WorkflowIncidents";
            """,
        };

        foreach (var sql in copyStatements)
        {
            try
            {
#pragma warning disable EF1002
                await db.Database.ExecuteSqlRawAsync(sql, cancellationToken);
#pragma warning restore EF1002
            }
            catch (Exception ex)
            {
                logger?.LogWarning(ex, "Copy statement warning: {Sql}", sql);
            }
        }

        // 7. Sync sequence values
        var seqStatements = new[]
        {
            $"SELECT setval(pg_get_serial_sequence('{validatedSchema}.\"WorkflowHistory\"', 'Id'), COALESCE((SELECT MAX(\"Id\") FROM {validatedSchema}.\"WorkflowHistory\"), 1));",
            $"SELECT setval(pg_get_serial_sequence('{validatedSchema}.\"WorkflowIncidents\"', 'Id'), COALESCE((SELECT MAX(\"Id\") FROM {validatedSchema}.\"WorkflowIncidents\"), 1));",
        };

        foreach (var sql in seqStatements)
        {
#pragma warning disable EF1002
            try { await db.Database.ExecuteSqlRawAsync(sql, cancellationToken); } catch { }
#pragma warning restore EF1002
        }

        // 8. Drop _old_* tables
        var dropStatements = new[]
        {
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowInstances\" CASCADE;",
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowInstanceData\" CASCADE;",
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowJobs\" CASCADE;",
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowHistory\" CASCADE;",
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowIncidents\" CASCADE;",
        };

        foreach (var sql in dropStatements)
        {
#pragma warning disable EF1002
            try { await db.Database.ExecuteSqlRawAsync(sql, cancellationToken); } catch { }
#pragma warning restore EF1002
        }

        logger?.LogInformation("Successfully migrated workflow tables in schema {Schema} to declarative partitioned tables.", targetSchema);
    }

    private static async Task EnsureWorkflowKeyDataBackfilledAsync(WorkflowDbContext db, string validatedSchema, CancellationToken cancellationToken)
    {
        var backfills = new[]
        {
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowInstanceData\" ADD COLUMN IF NOT EXISTS \"WorkflowKey\" varchar(128);",
            $"UPDATE {validatedSchema}.\"WorkflowInstanceData\" d SET \"WorkflowKey\" = COALESCE(i.\"WorkflowKey\", 'Default') FROM {validatedSchema}.\"WorkflowInstances\" i WHERE d.\"InstanceId\" = i.\"Id\" AND d.\"WorkflowKey\" IS NULL;",
            $"UPDATE {validatedSchema}.\"WorkflowInstanceData\" SET \"WorkflowKey\" = 'Default' WHERE \"WorkflowKey\" IS NULL;",

            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowJobs\" ADD COLUMN IF NOT EXISTS \"WorkflowKey\" varchar(128);",
            $"UPDATE {validatedSchema}.\"WorkflowJobs\" j SET \"WorkflowKey\" = COALESCE(i.\"WorkflowKey\", 'Default') FROM {validatedSchema}.\"WorkflowInstances\" i WHERE j.\"InstanceId\" = i.\"Id\" AND j.\"WorkflowKey\" IS NULL;",
            $"UPDATE {validatedSchema}.\"WorkflowJobs\" SET \"WorkflowKey\" = 'Default' WHERE \"WorkflowKey\" IS NULL;",

            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowHistory\" ADD COLUMN IF NOT EXISTS \"WorkflowKey\" varchar(128);",
            $"UPDATE {validatedSchema}.\"WorkflowHistory\" h SET \"WorkflowKey\" = COALESCE(i.\"WorkflowKey\", 'Default') FROM {validatedSchema}.\"WorkflowInstances\" i WHERE h.\"InstanceId\" = i.\"Id\" AND h.\"WorkflowKey\" IS NULL;",
            $"UPDATE {validatedSchema}.\"WorkflowHistory\" SET \"WorkflowKey\" = 'Default' WHERE \"WorkflowKey\" IS NULL;",

            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowIncidents\" ADD COLUMN IF NOT EXISTS \"WorkflowKey\" varchar(128);",
            $"UPDATE {validatedSchema}.\"WorkflowIncidents\" inc SET \"WorkflowKey\" = COALESCE(i.\"WorkflowKey\", 'Default') FROM {validatedSchema}.\"WorkflowInstances\" i WHERE inc.\"InstanceId\" = i.\"Id\" AND inc.\"WorkflowKey\" IS NULL;",
            $"UPDATE {validatedSchema}.\"WorkflowIncidents\" SET \"WorkflowKey\" = 'Default' WHERE \"WorkflowKey\" IS NULL;",
        };

        foreach (var sql in backfills)
        {
#pragma warning disable EF1002
            try { await db.Database.ExecuteSqlRawAsync(sql, cancellationToken); } catch { }
#pragma warning restore EF1002
        }
    }

    private static async Task ExecuteSafeAsync(WorkflowDbContext db, string sql, ILogger? logger, CancellationToken cancellationToken)
    {
        try
        {
#pragma warning disable EF1002
            await db.Database.ExecuteSqlRawAsync(sql, cancellationToken);
#pragma warning restore EF1002
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            logger?.LogDebug(ex, "Workflow partition statement skipped: {Sql}", sql);
        }
    }

    internal enum DataFilterOp
    {
        Default,
        Gte,
        Lte,
        Gt,
        Lt,
    }

    internal sealed record SqlDataCondition(string Property, string SqlOp, bool IsNumeric, object Parameter);

    internal sealed record InMemoryDataCondition(string Property, DataFilterOp Op, string Value, bool ExactString);

    internal static IEnumerable<(string Property, string Type)> ExtractIndexedProperties(WorkflowDefinition definition)
    {
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        if (definition.DataSchema?["properties"] is JsonObject dataProps)
        {
            foreach (var (propName, propVal) in dataProps)
            {
                if (propVal is not JsonObject propObj || !seen.Add(propName))
                {
                    continue;
                }

                // Never create B-Tree indexes on masked fields or fields with x-index: false.
                if (propObj[JsonSchemaValidator.MaskKeyword] is not null)
                {
                    continue;
                }

                var explicitIndex = propObj[JsonSchemaValidator.IndexKeyword] is JsonValue idxVal
                    && idxVal.GetValueKind() is JsonValueKind.True or JsonValueKind.False
                    ? idxVal.GetValue<bool>()
                    : (bool?)null;

                if (explicitIndex == false)
                {
                    continue;
                }

                var type = propObj["type"]?.GetValue<string>() ?? "string";
                var isEnum = propObj["enum"] is JsonArray { Count: > 0 };
                var isSearchable = propObj[JsonSchemaValidator.SearchKeyword] switch
                {
                    JsonValue sv when sv.GetValueKind() == JsonValueKind.True => true,
                    JsonValue sv when sv.GetValueKind() == JsonValueKind.String => !string.IsNullOrWhiteSpace(sv.GetValue<string>()),
                    _ => false,
                };

                // Only create a B-Tree index when explicitly requested (x-index: true) or when the field is searchable
                // with an SQL-pushable operator (enum equality or numeric/boolean comparison).
                if (explicitIndex == true || (isSearchable && (isEnum || type is "number" or "integer" or "boolean")))
                {
                    yield return (propName, type);
                }
            }
        }
    }

    internal static (string Property, DataFilterOp Op) ParseFilterKey(string rawKey)
    {
        ReadOnlySpan<(string Suffix, DataFilterOp Op)> suffixes =
        [
            ("_min", DataFilterOp.Gte),
            ("_gte", DataFilterOp.Gte),
            (".min", DataFilterOp.Gte),
            (".gte", DataFilterOp.Gte),
            ("_from", DataFilterOp.Gte),
            (".from", DataFilterOp.Gte),
            ("_max", DataFilterOp.Lte),
            ("_lte", DataFilterOp.Lte),
            (".max", DataFilterOp.Lte),
            (".lte", DataFilterOp.Lte),
            ("_to", DataFilterOp.Lte),
            (".to", DataFilterOp.Lte),
            ("_gt", DataFilterOp.Gt),
            (".gt", DataFilterOp.Gt),
            ("_lt", DataFilterOp.Lt),
            (".lt", DataFilterOp.Lt),
        ];

        foreach (var (suffix, op) in suffixes)
        {
            if (rawKey.Length > suffix.Length && rawKey.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
            {
                return (rawKey[..^suffix.Length], op);
            }
        }

        return (rawKey, DataFilterOp.Default);
    }

    internal static bool IsCreatedFromKey(string key) =>
        string.Equals(key, "createdFrom", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_from", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_min", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_gte", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt.from", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt.min", StringComparison.OrdinalIgnoreCase);

    internal static bool IsCreatedToKey(string key) =>
        string.Equals(key, "createdTo", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_to", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_max", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt_lte", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt.to", StringComparison.OrdinalIgnoreCase) ||
        string.Equals(key, "createdAt.max", StringComparison.OrdinalIgnoreCase);

    internal static bool TryParseDateBound(string? raw, bool inclusiveEndOfDay, out DateTime utc)
    {
        utc = default;
        if (string.IsNullOrWhiteSpace(raw))
        {
            return false;
        }

        var trimmed = raw.Trim();
        var isDateOnly = !trimmed.Contains('T', StringComparison.OrdinalIgnoreCase) && !trimmed.Contains(':', StringComparison.Ordinal);

        if (DateTime.TryParseExact(trimmed, ["yyyy-MM-dd", "dd.MM.yyyy"], CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal, out var exactDate))
        {
            utc = inclusiveEndOfDay
                ? DateTime.SpecifyKind(exactDate.Date.AddDays(1).AddTicks(-1), DateTimeKind.Utc)
                : DateTime.SpecifyKind(exactDate.Date, DateTimeKind.Utc);
            return true;
        }

        if (DateTimeOffset.TryParse(trimmed, CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal, out var dto))
        {
            var utcDt = dto.UtcDateTime;
            if (inclusiveEndOfDay && (isDateOnly || utcDt.TimeOfDay == TimeSpan.Zero))
            {
                utc = DateTime.SpecifyKind(utcDt.Date.AddDays(1).AddTicks(-1), DateTimeKind.Utc);
            }
            else
            {
                utc = DateTime.SpecifyKind(utcDt, DateTimeKind.Utc);
            }

            return true;
        }

        return false;
    }

    internal static bool TryParseDecimal(string? raw, out decimal number)
    {
        number = default;
        if (string.IsNullOrWhiteSpace(raw))
        {
            return false;
        }

        var normalized = raw.Trim().Replace(',', '.');
        return decimal.TryParse(normalized, NumberStyles.Float, CultureInfo.InvariantCulture, out number);
    }

    internal static bool TryGetNodeDecimal(JsonNode? node, out decimal number)
    {
        number = default;
        if (node is not JsonValue val)
        {
            return false;
        }

        if (val.GetValueKind() == JsonValueKind.Number)
        {
            if (val.TryGetValue<decimal>(out number))
            {
                return true;
            }

            return decimal.TryParse(val.ToJsonString(), NumberStyles.Float, CultureInfo.InvariantCulture, out number);
        }

        return val.GetValueKind() == JsonValueKind.String && TryParseDecimal(val.GetValue<string>(), out number);
    }

    /// <summary>
    /// Splits data property filters into SQL-indexable conditions (unmasked <c>enum</c> equality, numeric comparisons,
    /// and <c>CreatedAt</c> date bounds) and remaining filters evaluated on the projected JSON object.
    /// </summary>
    internal static (List<SqlDataCondition> SqlConditions, List<InMemoryDataCondition> RemainingConditions, DateTime? CreatedFromUtc, DateTime? CreatedToUtc) ClassifyDataFilters(
        IReadOnlyDictionary<string, string?>? rawFilters,
        JsonObject? projectedSchema)
    {
        var sqlConditions = new List<SqlDataCondition>();
        var remaining = new List<InMemoryDataCondition>();
        DateTime? createdFromUtc = null;
        DateTime? createdToUtc = null;

        if (rawFilters is null || rawFilters.Count == 0)
        {
            return (sqlConditions, remaining, createdFromUtc, createdToUtc);
        }

        var properties = projectedSchema?["properties"] as JsonObject;
        foreach (var (rawKey, rawValue) in rawFilters)
        {
            var key = rawKey?.Trim();
            var value = rawValue?.Trim();
            if (string.IsNullOrEmpty(key) || string.IsNullOrEmpty(value))
            {
                continue;
            }

            if (IsCreatedFromKey(key))
            {
                if (TryParseDateBound(value, inclusiveEndOfDay: false, out var from))
                {
                    createdFromUtc = from;
                }

                continue;
            }

            if (IsCreatedToKey(key))
            {
                if (TryParseDateBound(value, inclusiveEndOfDay: true, out var to))
                {
                    createdToUtc = to;
                }

                continue;
            }

            var (propName, op) = ParseFilterKey(key);
            if (properties?[propName] is JsonObject propSchema)
            {
                var isEnum = propSchema["enum"] is JsonArray { Count: > 0 };
                var isUnmasked = propSchema[JsonSchemaValidator.MaskKeyword] is null;
                var propType = propSchema["type"]?.GetValue<string>() ?? "string";
                var isNumeric = propType is "number" or "integer";

                if (isUnmasked && SafeIdRegex.IsMatch(propName))
                {
                    if (isEnum && op == DataFilterOp.Default)
                    {
                        sqlConditions.Add(new SqlDataCondition(propName, "=", IsNumeric: false, value));
                        continue;
                    }

                    if (isNumeric && TryParseDecimal(value, out var decValue))
                    {
                        var sqlOp = op switch
                        {
                            DataFilterOp.Gte => ">=",
                            DataFilterOp.Lte => "<=",
                            DataFilterOp.Gt => ">",
                            DataFilterOp.Lt => "<",
                            _ => "=",
                        };
                        sqlConditions.Add(new SqlDataCondition(propName, sqlOp, IsNumeric: true, decValue));
                        continue;
                    }
                }

                remaining.Add(new InMemoryDataCondition(propName, op, value, isEnum && op == DataFilterOp.Default));
            }
            else
            {
                remaining.Add(new InMemoryDataCondition(propName, op, value, ExactString: false));
            }
        }

        return (sqlConditions, remaining, createdFromUtc, createdToUtc);
    }

    /// <summary>
    /// Pushes <c>CreatedAt</c> date bounds, exact-match <c>enum</c> filters, and numeric comparison filters down to SQL
    /// using the flow partition functional B-Tree indexes (<c>IX_Part_{suffix}_{prop}</c>).
    /// </summary>
    internal static IQueryable<WorkflowInstance> ApplySqlDataFilters(
        IQueryable<WorkflowInstance> query,
        WorkflowDbContext db,
        string? schema,
        string workflowKey,
        IReadOnlyList<SqlDataCondition> sqlConditions,
        DateTime? createdFromUtc,
        DateTime? createdToUtc)
    {
        if (createdFromUtc is { } fromUtc)
        {
            query = query.Where(i => i.CreatedAt >= fromUtc);
        }

        if (createdToUtc is { } toUtc)
        {
            query = query.Where(i => i.CreatedAt <= toUtc);
        }

        if (sqlConditions.Count == 0)
        {
            return query;
        }

        var provider = db.Database.ProviderName ?? string.Empty;
        var isPostgres = provider.Contains("Npgsql", StringComparison.Ordinal);
        var isSqlite = provider.Contains("Sqlite", StringComparison.Ordinal);
        if (!isPostgres && !isSqlite)
        {
            return query;
        }

        var table = isPostgres ? $"{ValidateIdentifier(schema)}.\"WorkflowInstanceData\"" : "\"WorkflowInstanceData\"";
        var parameters = new List<object> { workflowKey };
        var clauses = new List<string>(sqlConditions.Count + 1) { "\"WorkflowKey\" = {0}" };

        foreach (var cond in sqlConditions)
        {
            if (!SafeIdRegex.IsMatch(cond.Property))
            {
                continue;
            }

            var idx = parameters.Count;
            if (cond.IsNumeric)
            {
                parameters.Add(isSqlite ? Convert.ToDouble(cond.Parameter, CultureInfo.InvariantCulture) : cond.Parameter);
                var expr = isPostgres
                    ? $"((((\"Data\"->>'{cond.Property}')::numeric))) {cond.SqlOp} {{{idx}}}"
                    : $"CAST(json_extract(\"Data\", '$.{cond.Property}') AS REAL) {cond.SqlOp} {{{idx}}}";
                clauses.Add(expr);
            }
            else
            {
                parameters.Add(cond.Parameter);
                var expr = isPostgres
                    ? $"((\"Data\"->>'{cond.Property}')::text) {cond.SqlOp} {{{idx}}}"
                    : $"json_extract(\"Data\", '$.{cond.Property}') {cond.SqlOp} {{{idx}}}";
                clauses.Add(expr);
            }
        }

        var sql = $"SELECT * FROM {table} WHERE {string.Join(" AND ", clauses)}";
#pragma warning disable EF1002
        var matchingData = db.InstanceData.FromSqlRaw(sql, [.. parameters]);
#pragma warning restore EF1002
        return query.Where(i => matchingData.Any(d => d.InstanceId == i.Id && d.WorkflowKey == i.WorkflowKey));
    }

    /// <summary>
    /// Evaluates remaining data conditions against a projected JSON object using numeric/date comparison or
    /// Turkish-aware and OrdinalIgnoreCase string comparison.
    /// </summary>
    internal static bool MatchesDataFilters(JsonObject? data, IReadOnlyList<InMemoryDataCondition> conditions)
    {
        if (conditions.Count == 0)
        {
            return true;
        }

        if (data is null)
        {
            return false;
        }

        foreach (var cond in conditions)
        {
            var node = data[cond.Property];
            if (node is null)
            {
                return false;
            }

            if (cond.Op is DataFilterOp.Gte or DataFilterOp.Lte or DataFilterOp.Gt or DataFilterOp.Lt)
            {
                if (TryGetNodeDecimal(node, out var actualDec) && TryParseDecimal(cond.Value, out var expectedDec))
                {
                    var ok = cond.Op switch
                    {
                        DataFilterOp.Gte => actualDec >= expectedDec,
                        DataFilterOp.Lte => actualDec <= expectedDec,
                        DataFilterOp.Gt => actualDec > expectedDec,
                        DataFilterOp.Lt => actualDec < expectedDec,
                        _ => actualDec == expectedDec,
                    };
                    if (!ok)
                    {
                        return false;
                    }

                    continue;
                }

                var actualDateStr = node is JsonValue dv && dv.GetValueKind() == JsonValueKind.String ? dv.GetValue<string>() : node.ToString();
                if (TryParseDateBound(actualDateStr, inclusiveEndOfDay: false, out var actualDate) &&
                    TryParseDateBound(cond.Value, inclusiveEndOfDay: cond.Op == DataFilterOp.Lte, out var expectedDate))
                {
                    var ok = cond.Op switch
                    {
                        DataFilterOp.Gte => actualDate >= expectedDate,
                        DataFilterOp.Lte => actualDate <= expectedDate,
                        DataFilterOp.Gt => actualDate > expectedDate,
                        DataFilterOp.Lt => actualDate < expectedDate,
                        _ => actualDate == expectedDate,
                    };
                    if (!ok)
                    {
                        return false;
                    }

                    continue;
                }

                return false;
            }

            var actual = node switch
            {
                JsonValue v when v.GetValueKind() == JsonValueKind.String => v.GetValue<string>(),
                JsonNode n => n.ToString(),
            };
            if (string.IsNullOrEmpty(actual))
            {
                return false;
            }

            if (cond.ExactString)
            {
                if (!string.Equals(actual, cond.Value, StringComparison.OrdinalIgnoreCase) &&
                    TrCompare.Compare(actual, cond.Value, CompareOptions.IgnoreCase) != 0)
                {
                    return false;
                }
            }
            else if (TryGetNodeDecimal(node, out var actualNum) && TryParseDecimal(cond.Value, out var expectedNum) && node is JsonValue { } jv && jv.GetValueKind() == JsonValueKind.Number)
            {
                if (actualNum != expectedNum)
                {
                    return false;
                }
            }
            else
            {
                if (!actual.Contains(cond.Value, StringComparison.OrdinalIgnoreCase) &&
                    TrCompare.IndexOf(actual, cond.Value, CompareOptions.IgnoreCase) < 0)
                {
                    return false;
                }
            }
        }

        return true;
    }

    private static string CleanIdentifier(string text) =>
        Regex.Replace(text, "[^A-Za-z0-9_]", "_");

    private static string ValidateIdentifier(string? name)
    {
        var safeName = string.IsNullOrWhiteSpace(name) ? "public" : name;
        return SafeIdRegex.IsMatch(safeName) ? $"\"{safeName}\"" : throw new InvalidOperationException($"Invalid SQL identifier '{name}'.");
    }
