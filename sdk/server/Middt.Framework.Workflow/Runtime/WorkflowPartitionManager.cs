namespace Middt.Framework.Workflow.Runtime;

/// <summary>
/// Manages PostgreSQL flow-based declarative partitioning and flow-specific JSON indexes for workflow tables.
/// </summary>
public static class WorkflowPartitionManager
{
    private static readonly Regex SafeIdRegex = new("^[A-Za-z_][A-Za-z0-9_]{0,63}$", RegexOptions.Compiled);

    /// <summary>Generates a PascalCase partition suffix from a kebab-case or snake_case workflow key.</summary>
    public static string PartitionSuffix(string workflowKey)
    {
        if (string.IsNullOrWhiteSpace(workflowKey))
        {
            return "Default";
        }

        var parts = workflowKey.Split(['-', '_', '.'], StringSplitOptions.RemoveEmptyEntries);
        return string.Concat(parts.Select(s => char.ToUpperInvariant(s[0]) + (s.Length > 1 ? s[1..] : string.Empty)));
    }

    /// <summary>
    /// Creates the 5 root partitioned tables in PostgreSQL if they do not exist yet.
    /// </summary>
    public static async Task CreatePartitionedTablesAsync(WorkflowDbContext db, string? schema, CancellationToken cancellationToken)
    {
        var validatedSchema = ValidateIdentifier(schema);
        var statements = new[]
        {
            $"""
            CREATE TABLE IF NOT EXISTS {validatedSchema}."WorkflowInstances" (
                "Id" uuid NOT NULL,
                "WorkflowKey" varchar(128) NOT NULL,
                "WorkflowVersion" int NOT NULL,
                "BusinessKey" varchar(256),
                "State" varchar(128) NOT NULL,
                "Status" varchar(16) NOT NULL,
                "PendingTransition" varchar(128),
                "PendingInput" text,
                "StartedBy" varchar(256),
                "LastExecutedBy" varchar(256),
                "Revision" int NOT NULL DEFAULT 0,
                "BusySince" timestamptz,
                "ParentInstanceId" uuid,
                "WaitingForInstanceId" uuid,
                "Error" text,
                "CreatedAt" timestamptz NOT NULL,
                "UpdatedAt" timestamptz NOT NULL,
                "CompletedAt" timestamptz,
                CONSTRAINT "PK_WorkflowInstances" PRIMARY KEY ("Id", "WorkflowKey")
            ) PARTITION BY LIST ("WorkflowKey");
            """,
            $"""
            CREATE TABLE IF NOT EXISTS {validatedSchema}."WorkflowInstanceData" (
                "InstanceId" uuid NOT NULL,
                "WorkflowKey" varchar(128) NOT NULL,
                "Data" jsonb NOT NULL,
                "DataVersion" int NOT NULL DEFAULT 0,
                "DataHash" varchar(64) NOT NULL,
                "ETag" varchar(64) NOT NULL,
                "UpdatedAt" timestamptz NOT NULL,
                CONSTRAINT "PK_WorkflowInstanceData" PRIMARY KEY ("InstanceId", "WorkflowKey"),
                CONSTRAINT "FK_WorkflowInstanceData_Instances" FOREIGN KEY ("InstanceId", "WorkflowKey")
                    REFERENCES {validatedSchema}."WorkflowInstances" ("Id", "WorkflowKey") ON DELETE CASCADE
            ) PARTITION BY LIST ("WorkflowKey");
            """,
            $"""
            CREATE TABLE IF NOT EXISTS {validatedSchema}."WorkflowHistory" (
                "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
                "InstanceId" uuid NOT NULL,
                "WorkflowKey" varchar(128) NOT NULL,
                "TransitionKey" varchar(128) NOT NULL,
                "FromState" varchar(128),
                "ToState" varchar(128) NOT NULL,
                "Trigger" varchar(16) NOT NULL,
                "ExecutedBy" varchar(256),
                "Input" jsonb,
                "DataVersion" int NOT NULL,
                "Data" jsonb NOT NULL,
                "Tasks" jsonb,
                "StartedAt" timestamptz NOT NULL,
                "FinishedAt" timestamptz NOT NULL,
                CONSTRAINT "PK_WorkflowHistory" PRIMARY KEY ("Id", "WorkflowKey")
            ) PARTITION BY LIST ("WorkflowKey");
            """,
            $"""
            CREATE TABLE IF NOT EXISTS {validatedSchema}."WorkflowJobs" (
                "Id" uuid NOT NULL,
                "InstanceId" uuid NOT NULL,
                "WorkflowKey" varchar(128) NOT NULL,
                "Kind" varchar(16) NOT NULL,
                "TransitionKey" varchar(128),
                "State" varchar(128),
                "Payload" jsonb,
                "RequestedBy" varchar(256),
                "DueAt" timestamptz NOT NULL,
                "LockedUntil" timestamptz,
                "Attempts" int NOT NULL DEFAULT 0,
                "LastError" text,
                "CreatedAt" timestamptz NOT NULL,
                CONSTRAINT "PK_WorkflowJobs" PRIMARY KEY ("Id", "WorkflowKey")
            ) PARTITION BY LIST ("WorkflowKey");
            """,
            $"""
            CREATE TABLE IF NOT EXISTS {validatedSchema}."WorkflowIncidents" (
                "Id" bigint GENERATED BY DEFAULT AS IDENTITY,
                "InstanceId" uuid NOT NULL,
                "WorkflowKey" varchar(128) NOT NULL,
                "State" varchar(128),
                "TransitionKey" varchar(128),
                "TaskKey" varchar(128),
                "Error" text NOT NULL,
                "Attempts" int NOT NULL DEFAULT 1,
                "CreatedAt" timestamptz NOT NULL,
                "ResolvedAt" timestamptz,
                CONSTRAINT "PK_WorkflowIncidents" PRIMARY KEY ("Id", "WorkflowKey")
            ) PARTITION BY LIST ("WorkflowKey");
            """,
        };

        foreach (var sql in statements)
        {
#pragma warning disable EF1002
            await db.Database.ExecuteSqlRawAsync(sql, cancellationToken);
#pragma warning restore EF1002
        }
    }

    /// <summary>
    /// Ensures flow partitions and flow-specific indexes exist for all registered workflows.
    /// </summary>
    public static async Task EnsurePartitionsAndIndexesAsync(
        WorkflowDbContext db,
        WorkflowRegistry registry,
        string? schema,
        ILogger? logger,
        CancellationToken cancellationToken)
    {
        var provider = db.Database.ProviderName ?? string.Empty;
        var isPostgres = provider.Contains("Npgsql", StringComparison.Ordinal);
        var isSqlite = provider.Contains("Sqlite", StringComparison.Ordinal);

        if (!isPostgres && !isSqlite)
        {
            return;
        }

        var validatedSchema = isPostgres ? ValidateIdentifier(schema) : string.Empty;
        var isPartitioned = isPostgres && await IsPartitionedTableAsync(db, schema, "WorkflowInstances", cancellationToken);

        if (isPostgres && !isPartitioned)
        {
            var unpartitionedExists = await IsUnpartitionedTableAsync(db, schema, "WorkflowInstances", cancellationToken);
            if (unpartitionedExists)
            {
                await MigrateExistingTablesToPartitionedAsync(db, registry, schema, logger, cancellationToken);
                isPartitioned = true;
            }
        }

        if (isPostgres && isPartitioned)
        {
            await EnsureDefaultPartitionsAsync(db, validatedSchema, logger, cancellationToken);
        }

        foreach (var definition in registry.Latest)
        {
            var workflowKey = definition.Key;
            var suffix = PartitionSuffix(workflowKey);

            if (isPostgres && isPartitioned)
            {
                await EnsureFlowPartitionsAsync(db, validatedSchema, workflowKey, suffix, logger, cancellationToken);
            }

            await EnsureFlowIndexesAsync(db, definition, validatedSchema, suffix, isPostgres, isPartitioned, logger, cancellationToken);
        }

        if (isPostgres)
        {
            await EnsureGlobalIndexesAsync(db, validatedSchema, logger, cancellationToken);
        }
    }

    private static async Task EnsureDefaultPartitionsAsync(WorkflowDbContext db, string schema, ILogger? logger, CancellationToken cancellationToken)
    {
        var defaultTables = new[]
        {
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowInstances_Default\" PARTITION OF {schema}.\"WorkflowInstances\" DEFAULT;",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowInstanceData_Default\" PARTITION OF {schema}.\"WorkflowInstanceData\" DEFAULT;",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowHistory_Default\" PARTITION OF {schema}.\"WorkflowHistory\" DEFAULT;",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowJobs_Default\" PARTITION OF {schema}.\"WorkflowJobs\" DEFAULT;",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowIncidents_Default\" PARTITION OF {schema}.\"WorkflowIncidents\" DEFAULT;",
        };

        foreach (var sql in defaultTables)
        {
            await ExecuteSafeAsync(db, sql, logger, cancellationToken);
        }
    }

    private static async Task EnsureFlowPartitionsAsync(WorkflowDbContext db, string schema, string workflowKey, string suffix, ILogger? logger, CancellationToken cancellationToken)
    {
        var escapedKey = workflowKey.Replace("'", "''", StringComparison.Ordinal);
        var partitionSqls = new[]
        {
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowInstances_{suffix}\" PARTITION OF {schema}.\"WorkflowInstances\" FOR VALUES IN ('{escapedKey}');",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowInstanceData_{suffix}\" PARTITION OF {schema}.\"WorkflowInstanceData\" FOR VALUES IN ('{escapedKey}');",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowHistory_{suffix}\" PARTITION OF {schema}.\"WorkflowHistory\" FOR VALUES IN ('{escapedKey}');",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowJobs_{suffix}\" PARTITION OF {schema}.\"WorkflowJobs\" FOR VALUES IN ('{escapedKey}');",
            $"CREATE TABLE IF NOT EXISTS {schema}.\"WorkflowIncidents_{suffix}\" PARTITION OF {schema}.\"WorkflowIncidents\" FOR VALUES IN ('{escapedKey}');",
        };

        foreach (var sql in partitionSqls)
        {
            await ExecuteSafeAsync(db, sql, logger, cancellationToken);
        }
    }

    private static async Task EnsureFlowIndexesAsync(
        WorkflowDbContext db,
        WorkflowDefinition definition,
        string schema,
        string suffix,
        bool isPostgres,
        bool isPartitioned,
        ILogger? logger,
        CancellationToken cancellationToken)
    {
        var targetTable = isPostgres && isPartitioned
            ? $"{schema}.\"WorkflowInstanceData_{suffix}\""
            : (isPostgres ? $"{schema}.\"WorkflowInstanceData\"" : "\"WorkflowInstanceData\"");

        var escapedKey = definition.Key.Replace("'", "''", StringComparison.Ordinal);

        foreach (var (propName, propType) in ExtractIndexedProperties(definition))
        {
            var cleanProp = CleanIdentifier(propName);
            var indexName = $"IX_Part_{suffix}_{cleanProp}";

            string sql;
            if (isPostgres && isPartitioned)
            {
                var expr = propType switch
                {
                    "number" or "integer" => $"((((\"Data\"->>'{propName}')::numeric)))",
                    "boolean" => $"((((\"Data\"->>'{propName}')::boolean)))",
                    _ => $"(((\"Data\"->>'{propName}')::text))",
                };
                sql = $"CREATE INDEX IF NOT EXISTS \"{indexName}\" ON {targetTable} ({expr});";
            }
            else if (isPostgres)
            {
                var expr = propType switch
                {
                    "number" or "integer" => $"((((\"Data\"->>'{propName}')::numeric)))",
                    "boolean" => $"((((\"Data\"->>'{propName}')::boolean)))",
                    _ => $"(((\"Data\"->>'{propName}')::text))",
                };
                sql = $"CREATE INDEX IF NOT EXISTS \"{indexName}\" ON {targetTable} ({expr}) WHERE \"WorkflowKey\" = '{escapedKey}';";
            }
            else
            {
                sql = $"CREATE INDEX IF NOT EXISTS \"{indexName}\" ON {targetTable} (json_extract(\"Data\", '$.{propName}')) WHERE \"WorkflowKey\" = '{escapedKey}';";
            }

            await ExecuteSafeAsync(db, sql, logger, cancellationToken);
        }
    }

    private static async Task EnsureGlobalIndexesAsync(WorkflowDbContext db, string schema, ILogger? logger, CancellationToken cancellationToken)
    {
        var globalIndexStatements = new[]
        {
            $"CREATE INDEX IF NOT EXISTS \"IX_WorkflowInstanceData_Data_GIN\" ON {schema}.\"WorkflowInstanceData\" USING gin (\"Data\" jsonb_path_ops);",
            $"CREATE INDEX IF NOT EXISTS \"IX_WorkflowHistory_Data_GIN\" ON {schema}.\"WorkflowHistory\" USING gin (\"Data\" jsonb_path_ops);",
        };

        foreach (var sql in globalIndexStatements)
        {
            await ExecuteSafeAsync(db, sql, logger, cancellationToken);
        }
    }

    private static async Task<bool> IsPartitionedTableAsync(WorkflowDbContext db, string? schema, string table, CancellationToken cancellationToken)
    {
        try
        {
            var targetSchema = string.IsNullOrWhiteSpace(schema) ? "public" : schema;
            var count = await db.Database.SqlQuery<int>($"""
                SELECT CAST(COUNT(*) AS int) AS "Value"
                FROM pg_partitioned_table pt
                JOIN pg_class c ON pt.partrelid = c.oid
                JOIN pg_namespace n ON c.relnamespace = n.oid
                WHERE n.nspname = {targetSchema} AND c.relname = {table}
                """).SingleAsync(cancellationToken);
            return count > 0;
        }
        catch
        {
            return false;
        }
    }

    private static async Task<bool> IsUnpartitionedTableAsync(WorkflowDbContext db, string? schema, string table, CancellationToken cancellationToken)
    {
        try
        {
            var targetSchema = string.IsNullOrWhiteSpace(schema) ? "public" : schema;
            var count = await db.Database.SqlQuery<int>($"""
                SELECT CAST(COUNT(*) AS int) AS "Value"
                FROM pg_class c
                JOIN pg_namespace n ON c.relnamespace = n.oid
                WHERE n.nspname = {targetSchema} AND c.relname = {table} AND c.relkind = 'r'
                """).SingleAsync(cancellationToken);
            return count > 0;
        }
        catch
        {
            return false;
        }
    }

    private static async Task MigrateExistingTablesToPartitionedAsync(
        WorkflowDbContext db,
        WorkflowRegistry registry,
        string? schema,
        ILogger? logger,
        CancellationToken cancellationToken)
    {
        var validatedSchema = ValidateIdentifier(schema);
        var targetSchema = string.IsNullOrWhiteSpace(schema) ? "public" : schema;

        logger?.LogInformation("Migrating workflow tables in schema {Schema} to declarative partitioned tables...", targetSchema);

        // 1. Ensure WorkflowKey column is populated on all 5 existing tables
        await EnsureWorkflowKeyDataBackfilledAsync(db, validatedSchema, cancellationToken);

        // 2. Drop existing foreign key and rename tables to temporary names
        var renameStatements = new[]
        {
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowInstanceData\" DROP CONSTRAINT IF EXISTS \"FK_WorkflowInstanceData_WorkflowInstances_InstanceId\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowInstanceData\" DROP CONSTRAINT IF EXISTS \"FK_WorkflowInstanceData_Instances\";",

            $"ALTER TABLE {validatedSchema}.\"WorkflowInstances\" RENAME TO \"_old_WorkflowInstances\";",
            $"ALTER TABLE {validatedSchema}.\"WorkflowInstanceData\" RENAME TO \"_old_WorkflowInstanceData\";",
            $"ALTER TABLE {validatedSchema}.\"WorkflowJobs\" RENAME TO \"_old_WorkflowJobs\";",
            $"ALTER TABLE {validatedSchema}.\"WorkflowHistory\" RENAME TO \"_old_WorkflowHistory\";",
            $"ALTER TABLE {validatedSchema}.\"WorkflowIncidents\" RENAME TO \"_old_WorkflowIncidents\";",

            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowInstances\" RENAME CONSTRAINT \"PK_WorkflowInstances\" TO \"_old_PK_WorkflowInstances\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowInstanceData\" RENAME CONSTRAINT \"PK_WorkflowInstanceData\" TO \"_old_PK_WorkflowInstanceData\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowJobs\" RENAME CONSTRAINT \"PK_WorkflowJobs\" TO \"_old_PK_WorkflowJobs\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowHistory\" RENAME CONSTRAINT \"PK_WorkflowHistory\" TO \"_old_PK_WorkflowHistory\";",
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowIncidents\" RENAME CONSTRAINT \"PK_WorkflowIncidents\" TO \"_old_PK_WorkflowIncidents\";",
        };

        foreach (var sql in renameStatements)
        {
            try
            {
#pragma warning disable EF1002
                await db.Database.ExecuteSqlRawAsync(sql, cancellationToken);
#pragma warning restore EF1002
            }
            catch (Exception ex)
            {
                logger?.LogDebug(ex, "Rename statement skipped: {Sql}", sql);
            }
        }

        // Drop any indexes on the old tables so index names are free for the new partitioned tables
        var dropOldIndexes = $"""
            DO $$
            DECLARE
                r RECORD;
            BEGIN
                FOR r IN (
                    SELECT indexname
                    FROM pg_indexes
                    WHERE schemaname = '{targetSchema}'
                      AND tablename IN ('_old_WorkflowInstances', '_old_WorkflowInstanceData', '_old_WorkflowJobs', '_old_WorkflowHistory', '_old_WorkflowIncidents')
                ) LOOP
                    EXECUTE 'DROP INDEX IF EXISTS {validatedSchema}."' || r.indexname || '" CASCADE;';
                END LOOP;
            END $$;
        """;
#pragma warning disable EF1002
        try { await db.Database.ExecuteSqlRawAsync(dropOldIndexes, cancellationToken); } catch { }
#pragma warning restore EF1002

        // 3. Create the 5 partitioned root tables
        await CreatePartitionedTablesAsync(db, schema, cancellationToken);

        // 4. Ensure default fallback partitions
        await EnsureDefaultPartitionsAsync(db, validatedSchema, logger, cancellationToken);

        // 5. Ensure flow-specific partitions for all registered flows
        foreach (var definition in registry.Latest)
        {
            var suffix = PartitionSuffix(definition.Key);
            await EnsureFlowPartitionsAsync(db, validatedSchema, definition.Key, suffix, logger, cancellationToken);
        }

        // 6. Copy all existing data from _old_* tables into the newly created partitioned tables
        var copyStatements = new[]
        {
            $"""
            INSERT INTO {validatedSchema}."WorkflowInstances"
            SELECT "Id", "WorkflowKey", "WorkflowVersion", "BusinessKey", "State", "Status",
                   "PendingTransition", "PendingInput", "StartedBy", "LastExecutedBy", "Revision",
                   "BusySince", "ParentInstanceId", "WaitingForInstanceId", "Error", "CreatedAt",
                   "UpdatedAt", "CompletedAt"
            FROM {validatedSchema}."_old_WorkflowInstances";
            """,
            $"""
            INSERT INTO {validatedSchema}."WorkflowInstanceData"
            SELECT "InstanceId", "WorkflowKey", "Data", "DataVersion", "DataHash", "ETag", "UpdatedAt"
            FROM {validatedSchema}."_old_WorkflowInstanceData";
            """,
            $"""
            INSERT INTO {validatedSchema}."WorkflowJobs"
            SELECT "Id", "InstanceId", "WorkflowKey", "Kind", "TransitionKey", "State", "Payload",
                   "RequestedBy", "DueAt", "LockedUntil", "Attempts", "LastError", "CreatedAt"
            FROM {validatedSchema}."_old_WorkflowJobs";
            """,
            $"""
            INSERT INTO {validatedSchema}."WorkflowHistory"
            SELECT "Id", "InstanceId", "WorkflowKey", "TransitionKey", "FromState", "ToState",
                   "Trigger", "ExecutedBy", "Input", "DataVersion", "Data", "Tasks", "StartedAt",
                   "FinishedAt"
            FROM {validatedSchema}."_old_WorkflowHistory";
            """,
            $"""
            INSERT INTO {validatedSchema}."WorkflowIncidents"
            SELECT "Id", "InstanceId", "WorkflowKey", "State", "TransitionKey", "TaskKey", "Error",
                   "Attempts", "CreatedAt", "ResolvedAt"
            FROM {validatedSchema}."_old_WorkflowIncidents";
            """,
        };

        foreach (var sql in copyStatements)
        {
            try
            {
#pragma warning disable EF1002
                await db.Database.ExecuteSqlRawAsync(sql, cancellationToken);
#pragma warning restore EF1002
            }
            catch (Exception ex)
            {
                logger?.LogWarning(ex, "Copy statement warning: {Sql}", sql);
            }
        }

        // 7. Sync sequence values
        var seqStatements = new[]
        {
            $"SELECT setval(pg_get_serial_sequence('{validatedSchema}.\"WorkflowHistory\"', 'Id'), COALESCE((SELECT MAX(\"Id\") FROM {validatedSchema}.\"WorkflowHistory\"), 1));",
            $"SELECT setval(pg_get_serial_sequence('{validatedSchema}.\"WorkflowIncidents\"', 'Id'), COALESCE((SELECT MAX(\"Id\") FROM {validatedSchema}.\"WorkflowIncidents\"), 1));",
        };

        foreach (var sql in seqStatements)
        {
#pragma warning disable EF1002
            try { await db.Database.ExecuteSqlRawAsync(sql, cancellationToken); } catch { }
#pragma warning restore EF1002
        }

        // 8. Drop _old_* tables
        var dropStatements = new[]
        {
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowInstances\" CASCADE;",
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowInstanceData\" CASCADE;",
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowJobs\" CASCADE;",
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowHistory\" CASCADE;",
            $"DROP TABLE IF EXISTS {validatedSchema}.\"_old_WorkflowIncidents\" CASCADE;",
        };

        foreach (var sql in dropStatements)
        {
#pragma warning disable EF1002
            try { await db.Database.ExecuteSqlRawAsync(sql, cancellationToken); } catch { }
#pragma warning restore EF1002
        }

        logger?.LogInformation("Successfully migrated workflow tables in schema {Schema} to declarative partitioned tables.", targetSchema);
    }

    private static async Task EnsureWorkflowKeyDataBackfilledAsync(WorkflowDbContext db, string validatedSchema, CancellationToken cancellationToken)
    {
        var backfills = new[]
        {
            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowInstanceData\" ADD COLUMN IF NOT EXISTS \"WorkflowKey\" varchar(128);",
            $"UPDATE {validatedSchema}.\"WorkflowInstanceData\" d SET \"WorkflowKey\" = COALESCE(i.\"WorkflowKey\", 'Default') FROM {validatedSchema}.\"WorkflowInstances\" i WHERE d.\"InstanceId\" = i.\"Id\" AND d.\"WorkflowKey\" IS NULL;",
            $"UPDATE {validatedSchema}.\"WorkflowInstanceData\" SET \"WorkflowKey\" = 'Default' WHERE \"WorkflowKey\" IS NULL;",

            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowJobs\" ADD COLUMN IF NOT EXISTS \"WorkflowKey\" varchar(128);",
            $"UPDATE {validatedSchema}.\"WorkflowJobs\" j SET \"WorkflowKey\" = COALESCE(i.\"WorkflowKey\", 'Default') FROM {validatedSchema}.\"WorkflowInstances\" i WHERE j.\"InstanceId\" = i.\"Id\" AND j.\"WorkflowKey\" IS NULL;",
            $"UPDATE {validatedSchema}.\"WorkflowJobs\" SET \"WorkflowKey\" = 'Default' WHERE \"WorkflowKey\" IS NULL;",

            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowHistory\" ADD COLUMN IF NOT EXISTS \"WorkflowKey\" varchar(128);",
            $"UPDATE {validatedSchema}.\"WorkflowHistory\" h SET \"WorkflowKey\" = COALESCE(i.\"WorkflowKey\", 'Default') FROM {validatedSchema}.\"WorkflowInstances\" i WHERE h.\"InstanceId\" = i.\"Id\" AND h.\"WorkflowKey\" IS NULL;",
            $"UPDATE {validatedSchema}.\"WorkflowHistory\" SET \"WorkflowKey\" = 'Default' WHERE \"WorkflowKey\" IS NULL;",

            $"ALTER TABLE IF EXISTS {validatedSchema}.\"WorkflowIncidents\" ADD COLUMN IF NOT EXISTS \"WorkflowKey\" varchar(128);",
            $"UPDATE {validatedSchema}.\"WorkflowIncidents\" inc SET \"WorkflowKey\" = COALESCE(i.\"WorkflowKey\", 'Default') FROM {validatedSchema}.\"WorkflowInstances\" i WHERE inc.\"InstanceId\" = i.\"Id\" AND inc.\"WorkflowKey\" IS NULL;",
            $"UPDATE {validatedSchema}.\"WorkflowIncidents\" SET \"WorkflowKey\" = 'Default' WHERE \"WorkflowKey\" IS NULL;",
        };

        foreach (var sql in backfills)
        {
#pragma warning disable EF1002
            try { await db.Database.ExecuteSqlRawAsync(sql, cancellationToken); } catch { }
#pragma warning restore EF1002
        }
    }

    private static async Task ExecuteSafeAsync(WorkflowDbContext db, string sql, ILogger? logger, CancellationToken cancellationToken)
    {
        try
        {
#pragma warning disable EF1002
            await db.Database.ExecuteSqlRawAsync(sql, cancellationToken);
#pragma warning restore EF1002
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            logger?.LogDebug(ex, "Workflow partition statement skipped: {Sql}", sql);
        }
    }

    private static IEnumerable<(string Property, string Type)> ExtractIndexedProperties(WorkflowDefinition definition)
    {
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        if (definition.DataSchema?["properties"] is JsonObject dataProps)
        {
            foreach (var (propName, propVal) in dataProps)
            {
                if (propVal is JsonObject propObj && seen.Add(propName))
                {
                    var type = propObj["type"]?.GetValue<string>() ?? "string";
                    yield return (propName, type);
                }
            }
        }

        if (definition.Start.Input?.Schema?["properties"] is JsonObject inputProps)
        {
            foreach (var (propName, propVal) in inputProps)
            {
                if (propVal is JsonObject propObj && seen.Add(propName))
                {
                    var type = propObj["type"]?.GetValue<string>() ?? "string";
                    yield return (propName, type);
                }
            }
        }
    }

    private static string CleanIdentifier(string text) =>
        Regex.Replace(text, "[^A-Za-z0-9_]", "_");

    private static string ValidateIdentifier(string? name)
    {
        var safeName = string.IsNullOrWhiteSpace(name) ? "public" : name;
        return SafeIdRegex.IsMatch(safeName) ? $"\"{safeName}\"" : throw new InvalidOperationException($"Invalid SQL identifier '{name}'.");
    }
